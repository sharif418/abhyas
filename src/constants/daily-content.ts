/**
 * Returns today's entry, based on day-of-year modulo pool length.
 * The same entry is shown all day and rotates at midnight — matching
 * the existing getDailyQuote() convention.
 */
export function getDailyContent(): DailyContent {
  const now = new Date();
  const start = new Date(now.getFullYear(), 0, 0);
  const diff = now.getTime() - start.getTime();
  const dayOfYear = Math.floor(diff / 86400000);
  return DAILY_CONTENT[dayOfYear % DAILY_CONTENT.length];
}
